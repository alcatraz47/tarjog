"""Write rendered files without clobbering files this tool did not generate."""

from __future__ import annotations

import json
import shutil
import time
from pathlib import Path

from . import is_generated
from .render import FileOutput


def _is_ours(path: Path) -> bool:
    if path.is_symlink():
        return True  # left over from the old symlink-based install
    if not path.exists():
        return True
    try:
        return is_generated(path.read_text())
    except (OSError, UnicodeDecodeError):
        return False


def _replace_symlinked_parent(path: Path) -> None:
    """Skill dirs used to be symlinks into the repo; never write through them."""
    if path.parent.is_symlink():
        path.parent.unlink()


def apply_output(output: FileOutput, dry_run: bool) -> str:
    path = output.path
    if not _is_ours(path):
        return f"skip   {path} (exists and was not generated by this tool)"
    if output.content is None:
        if not (path.exists() or path.is_symlink()):
            return f"absent {path}"
        if not dry_run:
            path.unlink()
        return f"remove {path}"
    if path.exists() and not path.is_symlink() and path.read_text() == output.content:
        return f"same   {path}"
    if not dry_run:
        _replace_symlinked_parent(path)
        if path.is_symlink():
            path.unlink()
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(output.content)
    return f"write  {path}"


def backup(path: Path, dry_run: bool) -> str | None:
    if not path.exists() or dry_run:
        return None
    target = path.with_name(f"{path.name}.bak-{time.strftime('%Y%m%d-%H%M%S')}")
    shutil.copy2(path, target)
    return f"backup {target}"


def write_json(path: Path, data: dict, dry_run: bool) -> list[str]:
    return write_text(path, json.dumps(data, indent=2) + "\n", dry_run)


def write_text(path: Path, content: str, dry_run: bool) -> list[str]:
    if path.exists() and path.read_text() == content:
        return [f"same   {path}"]
    log = [line for line in (backup(path, dry_run),) if line]
    if not dry_run:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    return log + [f"write  {path}"]
