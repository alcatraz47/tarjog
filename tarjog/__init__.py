"""tarjog (Bangla: tar = wire, jog = connection) — wires Claude Code to your routing,
review and project conventions from one config file."""

MARKER = "generated by tarjog"
# Files written before the rename carry the old marker; treat them as ours so they get migrated.
LEGACY_MARKERS = ("generated by personal-claude-routing",)
ALL_MARKERS = (MARKER, *LEGACY_MARKERS)


def is_generated(text: str) -> bool:
    return any(marker in text for marker in ALL_MARKERS)
